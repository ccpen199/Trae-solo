const generateBoundary = (centerLat: number, centerLng: number, size: number) => {
  const points = [];
  const steps = 8;
  for (let i = 0; i < steps; i++) {
    const angle = (i / steps) * 2 * Math.PI;
    const lat = centerLat + Math.sin(angle) * size * 0.5;
    const lng = centerLng + Math.cos(angle) * size * 0.6;
    points.push({ lat, lng });
  }
  return points;
};


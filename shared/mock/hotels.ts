function generateRatePlansForRoom(roomTypeId: string, basePrice: number, currency: Currency): RatePlan[] {
  const channels = ['stayglobal', 'booking.com', 'agoda', 'expedia', 'trip.com'];
  return channels.map((channel, index) => {
    const priceVariation = 0.9 + (index * 0.03) + (Math.random() * 0.05);
    const amount = Math.round(basePrice * priceVariation);
    const originalPrice = channel !== 'stayglobal' ? Math.round(amount * 1.1) : undefined;
    
    return {
      id: `rate-${roomTypeId}-${channel.replace('.', '-')}`,
      roomTypeId,
      channel,
      price: { amount, currency },
      originalPrice: originalPrice ? { amount: originalPrice, currency } : undefined,
      includesBreakfast: index % 2 === 0,
      isRefundable: index !== 4,
      status: RatePlanStatus.ACTIVE,
    };
  });
}


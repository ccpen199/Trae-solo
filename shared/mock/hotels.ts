function calculateCompositeScore(price: number, rating: number, isRefundable: boolean, distance?: number): number {
  const priceScore = Math.max(0, 100 - (price / 100));
  const ratingScore = rating * 10;
  const flexibilityScore = isRefundable ? 90 : 60;
  const locationScore = distance ? Math.max(0, 100 - distance * 10) : 85;
  
  return (priceScore * 0.35) + (ratingScore * 0.25) + (flexibilityScore * 0.20) + (locationScore * 0.20);
}

export function getMockSearchResults(destination?: string): SearchResult[] {
  let filteredHotels = mockHotels;
  if (destination) {
    const destLower = destination.toLowerCase();
    filteredHotels = mockHotels.filter(h => 
      h.address.city.toLowerCase().includes(destLower) ||
      h.address.country.toLowerCase().includes(destLower) ||
      h.name.toLowerCase().includes(destLower)
    );
  }
  
  return filteredHotels.map(hotel => {
    const hotelRoomTypes = mockRoomTypes.filter(rt => rt.hotelId === hotel.id);
    const firstRoomType = hotelRoomTypes[0];
    const roomRatePlans = mockRatePlans.filter(rp => rp.roomTypeId === firstRoomType.id);
    const bestRate = roomRatePlans.reduce((best, current) => 
      current.price.amount < best.price.amount ? current : best
    , roomRatePlans[0]);
    
    const rateComparison = roomRatePlans.map(rp => ({
      channel: rp.channel,
      price: rp.price,
      savings: rp.originalPrice ? rp.originalPrice.amount - rp.price.amount : undefined,
    }));
    
    const compositeScore = calculateCompositeScore(
      bestRate.price.amount,
      hotel.overallRating,
      bestRate.isRefundable
    );
    
    return {
      id: `result-${hotel.id}`,
      hotel,
      roomTypes: hotelRoomTypes,
      bestRate,
      rateComparison,
      compositeScore,
    };
  }).sort((a, b) => b.compositeScore - a.compositeScore);
}


export function getMockOrders(status?: OrderStatus): Order[] {
  if (!status) return mockOrders
  return mockOrders.filter(o => o.status === status)
}

export function getMockSubOrders(farmerId?: string, status?: OrderStatus): SubOrder[] {
  let result = mockSubOrders
  if (farmerId) {
    result = result.filter(so => so.farmerId === farmerId)
  }
  if (status) {
    result = result.filter(so => so.status === status)
  }
  return result
}


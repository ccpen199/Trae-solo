export const getIRCodeLibrary = () => {
  const cached = getCache(LIBRARY_CACHE_KEY)
  if (cached) {
    return cached
  }
  setCache(LIBRARY_CACHE_KEY, defaultCodes, 30 * 24 * 60 * 60 * 1000)
  return defaultCodes
}

export const getIRCode = (deviceType, command) => {
  const library = getIRCodeLibrary()
  return library[deviceType]?.[command] || null
}

export const getDeviceCommands = (deviceType) => {
  const library = getIRCodeLibrary()
  const deviceCodes = library[deviceType] || {}
  return Object.keys(deviceCodes).map(command => ({
    command,
    ...deviceCodes[command]
  }))
}

export const addIRCode = (deviceType, command, codeData) => {
  const library = getIRCodeLibrary()
  if (!library[deviceType]) {
    library[deviceType] = {}
  }
  library[deviceType][command] = codeData
  setCache(LIBRARY_CACHE_KEY, library, 30 * 24 * 60 * 60 * 1000)
  return library
}

export const searchIRCodes = (query) => {
  const library = getIRCodeLibrary()
  const results = []
  const lowerQuery = query.toLowerCase()

  Object.entries(library).forEach(([deviceType, commands]) => {
    Object.entries(commands).forEach(([command, codeData]) => {
      if (
        deviceType.toLowerCase().includes(lowerQuery) ||
        command.toLowerCase().includes(lowerQuery) ||
        codeData.code.includes(query)
      ) {
        results.push({
          deviceType,
          command,
          ...codeData
        })
      }
    })
  })

  return results
}

export const getSupportedDeviceTypes = () => {
  const library = getIRCodeLibrary()
  return Object.keys(library)
}

export const updateLibraryFromCloud = (cloudLibrary) => {
  const library = getIRCodeLibrary()
  const merged = { ...library, ...cloudLibrary }
  setCache(LIBRARY_CACHE_KEY, merged, 30 * 24 * 60 * 60 * 1000)
  return merged
}

export const decodeRawIR = (rawCode) => {
  const parts = rawCode.trim().split(/\s+/)
  if (parts.length < 4) return null

  const header = parts.slice(0, 2)
  const data = parts.slice(2, -1)
  const trailing = parts[parts.length - 1]

  let format = 'UNKNOWN'
  if (header[0] === '0001' && header[1] === '0001') {
    format = 'NEC'
  } else if (header[0] === '0002' && header[1] === '0002') {
    format = 'NEC_EXTENDED'
  } else if (header[0] === '0004' && header[1] === '0001') {
    format = 'RC5'
  } else if (header[0] === '0000' && header[1] === '0071') {
    format = 'RC6'
  }

  return {
    format,
    frequency: 38000,
    bitCount: (data.length / 2),
    rawCode,
    header,
    data,
    trailing,
    hexCode: rawToHex(data)
  }
}

const rawToHex = (data) => {
  if (!data || data.length % 2 !== 0) return ''

  let hex = ''
  for (let i = 0; i < data.length; i += 2) {
    const short = parseInt(data[i], 16)
    const long = parseInt(data[i + 1], 16)
    hex += (long > short) ? '1' : '0'
  }

  let hexStr = ''
  for (let i = 0; i < hex.length; i += 4) {
    const nibble = hex.substr(i, 4)
    hexStr += parseInt(nibble, 2).toString(16).toUpperCase()
  }

  return '0x' + hexStr
}

export const encodeIRToRaw = (hexCode, format = 'NEC') => {
  const binary = hexToBinary(hexCode.replace('0x', ''))
  let raw = ''

  if (format === 'NEC') {
    raw = '0001 0001 '
    for (let i = 0; i < binary.length; i++) {
      if (binary[i] === '0') {
        raw += '0020 0020 '
      } else {
        raw += '0020 0040 '
      }
    }
    raw += '0020 0400'
  }

  return raw.toUpperCase()
}

const hexToBinary = (hex) => {
  return hex.split('').map(c =>
    parseInt(c, 16).toString(2).padStart(4, '0')
  ).join('')
}

export function getCities(provinceCode: string): { code: string; name: string }[] {
  const province = provinceData.find(p => p.code === provinceCode)
  if (!province || !province.children) return []
  return province.children.map(c => ({ code: c.code, name: c.name }))
}

export function getDistricts(provinceCode: string, cityCode: string): { code: string; name: string }[] {
  const province = provinceData.find(p => p.code === provinceCode)
  if (!province || !province.children) return []
  
  const city = province.children.find(c => c.code === cityCode)
  if (!city || !city.children) return []
  
  return city.children.map(d => ({ code: d.code, name: d.name }))
}

export function getProvinceName(provinceCode: string): string {
  const province = provinceData.find(p => p.code === provinceCode)
  return province?.name || ''
}

export function getCityName(provinceCode: string, cityCode: string): string {
  const province = provinceData.find(p => p.code === provinceCode)
  if (!province || !province.children) return ''
  
  const city = province.children.find(c => c.code === cityCode)
  return city?.name || ''
}

export function getDistrictName(provinceCode: string, cityCode: string, districtCode: string): string {
  const province = provinceData.find(p => p.code === provinceCode)
  if (!province || !province.children) return ''
  
  const city = province.children.find(c => c.code === cityCode)
  if (!city || !city.children) return ''
  
  const district = city.children.find(d => d.code === districtCode)
  return district?.name || ''
}


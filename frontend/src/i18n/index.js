function getNestedValue(obj, path) {
  return path.split('.').reduce((acc, key) => acc?.[key], obj);
}

export function useTranslation(language) {
  const translationsObj = translations[language] || translations.cn;
  const t = (path) => getNestedValue(translationsObj, path) || path;
  return { t };
}


function generateSeats(hallId: string, rows: number, cols: number, basePrice: number = 50): Seat[][] {
  const seats: Seat[][] = [];
  const goldenRowStart = Math.floor(rows * 0.35);
  const goldenRowEnd = Math.floor(rows * 0.55);
  const vipRowStart = Math.floor(rows * 0.7);
  const discountCols = cols <= 6 ? [0, cols - 1] : [0, 1, cols - 2, cols - 1];
  const rowLabels = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

  for (let r = 0; r < rows; r++) {
    const row: Seat[] = [];
    for (let c = 0; c < cols; c++) {
      let zone: SeatZone = 'standard';
      let price = basePrice;
      let isGoldenView = false;

      if (r >= vipRowStart) {
        zone = 'vip';
        price = Math.floor(basePrice * 1.5);
      } else if (r >= goldenRowStart && r <= goldenRowEnd) {
        zone = 'golden';
        isGoldenView = true;
        price = Math.floor(basePrice * 1.2);
      } else if (discountCols.includes(c)) {
        zone = 'premium';
        price = Math.floor(basePrice * 0.8);
      }

      const random = Math.random();
      let status: SeatStatus = 'available';
      if (random < 0.15) {
        status = 'sold';
      } else if (random < 0.2) {
        status = 'locked';
      }

      row.push({
        id: `seat_${hallId}_${r}_${c}`,
        row: rowLabels[r] || String(r + 1),
        col: c + 1,
        rowIndex: r,
        colIndex: c,
        status,
        zone,
        isGoldenView,
        price,
        isAvailable: status === 'available',
        hallId,
      });
    }
    seats.push(row);
  }

  return seats;
}

function createHall(
  id: string,
  name: string,
  type: Hall['type'],
  rows: number,
  cols: number,
  cinemaId: string
): Hall {
  return {
    id,
    name,
    type,
    totalSeats: rows * cols,
    rows,
    cols,
    cinemaId,
    seatLayout: generateSeats(id, rows, cols),
  };
}


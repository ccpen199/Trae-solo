const generateSlots = (count: number, fullCount: number, chargingCount: number) => {
  const slots = []
  for (let i = 1; i <= count; i++) {
    let status: 'empty' | 'occupied' | 'charging' | 'fault' | 'locked' = 'empty'
    let soc = 0
    let batteryId = undefined

    if (i <= fullCount) {
      status = 'occupied'
      soc = 95 + Math.floor(Math.random() * 5)
      batteryId = `BAT-2024-${String(i + 10).padStart(4, '0')}`
    } else if (i <= fullCount + chargingCount) {
      status = 'charging'
      soc = 30 + Math.floor(Math.random() * 40)
      batteryId = `BAT-2024-${String(i + 20).padStart(4, '0')}`
    }

    slots.push({
      slot_number: i,
      status,
      battery_id: batteryId,
      soc: status !== 'empty' ? soc : undefined,
      door_status: 'closed' as const,
    })
  }
  return slots
}


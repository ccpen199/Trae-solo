import type { Template, EditorLayer } from '@/types';

const createBackgroundLayer = (id: string, canvasWidth: number, canvasHeight: number, color: string): EditorLayer => ({
  id: `layer-${id}-bg`,
  type: 'background',
  name: '背景层',
  visible: true,
  locked: true,
  order: 100,
  x: 0,
  y: 0,
  width: canvasWidth,
  height: canvasHeight,
  rotation: 0,
  opacity: 1,
  shapeData: {
    shapeType: 'rectangle',
    fill: color,
    stroke: 'transparent',
    strokeWidth: 0,
    borderRadius: 0,
  },
});

const createTextLayer = (id: string, canvasWidth: number, canvasHeight: number, content: string, yOffset: number = 0): EditorLayer => ({
  id: `layer-${id}-text-1`,
  type: 'text',
  name: '标题文字',
  visible: true,
  locked: false,
  order: 10,
  x: canvasWidth * 0.1,
  y: canvasHeight * 0.1 + yOffset,
  width: canvasWidth * 0.8,
  height: 80,
  rotation: 0,
  opacity: 1,
  textData: {
    content,
    fontSize: 48,
    fontFamily: 'PingFang SC',
    fontWeight: 'bold',
    color: '#333333',
    textAlign: 'center',
    lineHeight: 1.2,
    letterSpacing: 2,
  },
});

const createDecorativeShapeLayer = (id: string, canvasWidth: number, canvasHeight: number, color: string): EditorLayer => ({
  id: `layer-${id}-shape-1`,
  type: 'shape',
  name: '装饰元素',
  visible: true,
  locked: false,
  order: 20,
  x: canvasWidth * 0.05,
  y: canvasHeight * 0.8,
  width: canvasWidth * 0.9,
  height: 4,
  rotation: 0,
  opacity: 0.6,
  shapeData: {
    shapeType: 'rectangle',
    fill: color,
    stroke: 'transparent',
    strokeWidth: 0,
    borderRadius: 2,
  },
});

const createImagePlaceholderLayer = (id: string, canvasWidth: number, canvasHeight: number): EditorLayer => ({
  id: `layer-${id}-image-1`,
  type: 'image',
  name: '图片占位',
  visible: true,
  locked: false,
  order: 30,
  x: canvasWidth * 0.1,
  y: canvasHeight * 0.25,
  width: canvasWidth * 0.8,
  height: canvasHeight * 0.5,
  rotation: 0,
  opacity: 1,
  imageData: {
    src: 'https://picsum.photos/seed/placeholder/800/600',
    originalWidth: 800,
    originalHeight: 600,
    objectFit: 'cover',
  },
});

const getTemplateLayers = (templateId: string, category: string, canvasWidth: number, canvasHeight: number): EditorLayer[] => {
  const layers: EditorLayer[] = [];

  switch (category) {
    case 'minimal':
      layers.push(
        createBackgroundLayer(templateId, canvasWidth, canvasHeight, '#FFFFFF'),
        createImagePlaceholderLayer(templateId, canvasWidth, canvasHeight),
        createTextLayer(templateId, canvasWidth, canvasHeight, '记录美好时光'),
        createDecorativeShapeLayer(templateId, canvasWidth, canvasHeight, '#E5E7EB')
      );
      break;
    case 'vintage':
      layers.push(
        createBackgroundLayer(templateId, canvasWidth, canvasHeight, '#F5F0E6'),
        createImagePlaceholderLayer(templateId, canvasWidth, canvasHeight),
        createTextLayer(templateId, canvasWidth, canvasHeight, '岁月留痕'),
        createDecorativeShapeLayer(templateId, canvasWidth, canvasHeight, '#8B7355')
      );
      break;
    case 'cute':
      layers.push(
        createBackgroundLayer(templateId, canvasWidth, canvasHeight, '#FFF5F7'),
        createImagePlaceholderLayer(templateId, canvasWidth, canvasHeight),
        createTextLayer(templateId, canvasWidth, canvasHeight, '甜蜜时刻'),
        createDecorativeShapeLayer(templateId, canvasWidth, canvasHeight, '#FFB6C1')
      );
      break;
    case 'business':
      layers.push(
        createBackgroundLayer(templateId, canvasWidth, canvasHeight, '#F8FAFC'),
        createImagePlaceholderLayer(templateId, canvasWidth, canvasHeight),
        createTextLayer(templateId, canvasWidth, canvasHeight, '精彩瞬间'),
        createDecorativeShapeLayer(templateId, canvasWidth, canvasHeight, '#3B82F6')
      );
      break;
    default:
      layers.push(
        createBackgroundLayer(templateId, canvasWidth, canvasHeight, '#FFFFFF'),
        createImagePlaceholderLayer(templateId, canvasWidth, canvasHeight),
        createTextLayer(templateId, canvasWidth, canvasHeight, '美好的回忆')
      );
  }

  return layers;
};


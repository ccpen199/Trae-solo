export interface CertificateCategory {
  id: string
  name: string
  icon: string
  count: number
}

export interface Certificate {
  id: string
  name: string
  category: string
  subCategory: string
  holderName: string
  holderId: string
  issueDate: string
  expiryDate: string
  status: 'valid' | 'expired' | 'expiring_soon'
  issuer: string
  credentialNo: string
}

export interface ExemptionScenario {
  id: string
  name: string
  department: string
  replacedCerts: string[]
  replacedCertIds: string[]
  description: string
  savingsTime: string
  callRecords: { date: string; success: boolean }[]
  formFields: { name: string; sourceCert: string; value: string }[]
  totalSavedTime: number
}

export interface AuthRecord {
  id: string
  party: string
  certIds: string[]
  authDate: string
  expiryDate: string
  status: 'active' | 'revoked' | 'expired'
  authScope: 'read' | 'verify' | 'full'
  callCount: number
  lastCalled: string
  revokeReason?: string
  revokeTime?: string
  revokeOperator?: string
  purpose?: string
}

export interface AuthAuditRecord {
  id: string
  authId: string
  action: 'grant' | 'revoke' | 'call' | 'expire'
  timestamp: string
  operator: string
  details: string
}

export interface SubCategory {
  id: string
  name: string
  parentId: string
  count: number
}


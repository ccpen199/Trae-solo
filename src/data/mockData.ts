const createMediaAssets = (
  artistName: string,
  gender: string,
  includeThreeView: boolean = true
): MediaAsset[] => {
  const assets: MediaAsset[] = [];
  const genderDesc = gender === 'female' ? 'female' : gender === 'male' ? 'male' : 'non-binary';

  assets.push({
    id: generateId(),
    type: 'photo',
    url: getImageUrl(`professional asian ${genderDesc} model portrait studio lighting high quality`),
    isPrimary: true,
    order: 0,
    metadata: { resolution: '2048x2048', photographer: 'studio' },
  });

  assets.push({
    id: generateId(),
    type: 'photo',
    url: getImageUrl(`asian ${genderDesc} model fashion editorial photoshoot natural light`),
    isPrimary: false,
    order: 1,
    metadata: { resolution: '2048x2048', location: 'outdoor' },
  });

  assets.push({
    id: generateId(),
    type: 'photo',
    url: getImageUrl(`asian ${genderDesc} model commercial portrait professional makeup`),
    isPrimary: false,
    order: 2,
    metadata: { resolution: '2048x2048', style: 'commercial' },
  });

  if (includeThreeView) {
    assets.push({
      id: generateId(),
      type: 'three_view',
      url: getImageUrl(`asian ${genderDesc} model three view measurement photo full body front side back`),
      isPrimary: false,
      order: 3,
      metadata: { resolution: '2048x2048', type: 'measurement' },
    });
  }

  return assets;
};

const createTags = (customTags: Array<{ tag: string; category: TalentTag['category']; weight: number }>): TalentTag[] => {
  return customTags.map((t) => ({
    id: generateId(),
    ...t,
  }));
};


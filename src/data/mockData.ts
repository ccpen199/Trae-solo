function generateSeats(storeId: string, count: number, startIndex: number): Seat[] {
  const seats: Seat[] = [];
  const areas = ['A', 'B', 'C'];
  const priceMap: Record<string, number> = { A: 15, B: 12, C: 10 };
  
  for (let i = 0; i < count; i++) {
    const area = areas[Math.floor(i / (count / 3)) % 3];
    const row = Math.floor((i % (count / 3)) / 6) + 1;
    const col = (i % 6) + 1;
    const statusRandom = Math.random();
    const status = statusRandom > 0.4 ? 'available' : statusRandom > 0.15 ? 'occupied' : statusRandom > 0.05 ? 'reserved' : 'maintenance';
    
    seats.push({
      id: `seat-${storeId}-${String(startIndex + i + 1).padStart(3, '0')}`,
      storeId,
      seatNumber: `${area}${row}-${col}`,
      area: `${area}区`,
      row,
      col,
      deviceId: `dev-${storeId}-pc-${String(i + 1).padStart(3, '0')}`,
      status,
      pricePerHour: priceMap[area],
      networkLatency: 10 + Math.random() * 30,
    });
  }
  return seats;
}


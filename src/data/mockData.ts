function generatePhone(): string {
  const prefixes = ['138', '139', '158', '159', '188', '189', '136', '137', '150', '151'];
  const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
  let suffix = '';
  for (let i = 0; i < 8; i++) {
    suffix += Math.floor(Math.random() * 10);
  }
  return prefix + suffix;
}

function generateName(): string {
  const firstName = firstNames[Math.floor(Math.random() * firstNames.length)];
  const lastName = lastNames[Math.floor(Math.random() * lastNames.length)];
  return firstName + lastName;
}

function getLevelByPoints(points: number): { level: number; levelName: string } {
  if (points >= 50000) return { level: 5, levelName: '钻石会员' };
  if (points >= 20000) return { level: 4, levelName: '铂金会员' };
  if (points >= 5000) return { level: 3, levelName: '黄金会员' };
  if (points >= 1000) return { level: 2, levelName: '白银会员' };
  return { level: 1, levelName: '青铜会员' };
}


export function getAnnualReportsByCompany(companyId: string): AnnualReport[] {
  return mockAnnualReports.filter(r => r.companyId === companyId);
}

export function getBondsByCompany(companyId: string): Bond[] {
  return mockBonds.filter(b => b.companyId === companyId);
}

export function getLandReservesByCompany(companyId: string): LandReserve[] {
  return mockLandReserves.filter(l => l.companyId === companyId);
}

export function getLatestReport(companyId: string): AnnualReport | undefined {
  const reports = getAnnualReportsByCompany(companyId);
  return reports.sort((a, b) => b.year - a.year)[0];
}

import type { Project, ProjectStage } from '../types/project';

const createStages = (landDate: string, constructionStart: string, salesStart: string, deliveryDate: string, status: 'active' | 'completed' | 'delayed'): ProjectStage[] => {
  const stages: ProjectStage[] = [
    { type: 'land-acquisition', status: 'completed', startDate: landDate, endDate: landDate, progress: 100 },
    {
      type: 'construction',
      status: status === 'completed' ? 'completed' : status === 'delayed' ? 'in-progress' : 'in-progress',
      startDate: constructionStart,
      endDate: status === 'completed' ? deliveryDate : undefined,
      progress: status === 'completed' ? 100 : status === 'delayed' ? 65 : 80,
    },
    {
      type: 'sales',
      status: 'in-progress',
      startDate: salesStart,
      progress: 70,
    },
    {
      type: 'delivery',
      status: status === 'completed' ? 'completed' : 'not-started',
      startDate: status === 'completed' ? deliveryDate : undefined,
      endDate: status === 'completed' ? deliveryDate : undefined,
      progress: status === 'completed' ? 100 : 0,
    },
  ];
  return stages;
};


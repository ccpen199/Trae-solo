export interface ServiceProvider {
  id: string
  name: string
  type: string
  icon: string
  phone: string
  website: string
  address: string
}

export interface Bill {
  id: string
  providerId: string
  providerName: string
  type: string
  amount: number
  date: string
  dueDate: string
  status: 'paid' | 'unpaid' | 'overdue'
  accountNo: string
  details: string
  hasInvoice: boolean
  hasVoucher: boolean
  currentStep: number
}

export interface Invoice {
  id: string
  billId: string
  providerName: string
  amount: number
  issueDate: string
  invoiceNo: string
  type: string
  downloadUrl: string
}

export interface PaymentRecord {
  id: string
  billId: string
  amount: number
  payTime: string
  payMethod: 'wechat' | 'alipay' | 'unionpay' | 'bank'
  transactionNo: string
  status: 'pending' | 'success' | 'failed' | 'refunded'
  operator: string
  remark?: string
}

export interface ReconciliationRecord {
  id: string
  billId: string
  paymentId: string
  reconciliationDate: string
  status: 'matched' | 'mismatch' | 'pending'
  systemAmount: number
  providerAmount: number
  difference: number
  remark?: string
}

export interface NonTaxVoucher {
  id: string
  billId: string
  paymentId: string
  voucherNo: string
  amount: number
  payerName: string
  payerIdNo: string
  itemName: string
  itemCode: string
  issueDate: string
  issuingAuthority: string
  verifyCode: string
  downloadUrl: string
  status: 'valid' | 'invalid'
}

export interface BusinessFlowLog {
  id: string
  billId: string
  action: string
  timestamp: string
  status: string
  details: string
  operator?: string
}


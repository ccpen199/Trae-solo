CREATE TABLE IF NOT EXISTS `api_info` (
  `id` bigint NOT NULL COMMENT '主键ID',
  `api_code` varchar(100) NOT NULL COMMENT 'API编码',
  `api_name` varchar(200) NOT NULL COMMENT 'API名称',
  `api_version` varchar(20) NOT NULL DEFAULT '1.0' COMMENT 'API版本',
  `api_desc` varchar(500) DEFAULT NULL COMMENT 'API描述',
  `request_method` varchar(10) NOT NULL COMMENT '请求方式: GET,POST,PUT,DELETE',
  `request_url` varchar(500) NOT NULL COMMENT '请求URL',
  `dept_code` varchar(50) NOT NULL COMMENT '所属部门编码',
  `dept_name` varchar(100) NOT NULL COMMENT '所属部门名称',
  `datasource_code` varchar(50) NOT NULL COMMENT '数据源编码',
  `status` tinyint NOT NULL DEFAULT '0' COMMENT '状态:0-草稿,1-已发布,2-已下线,3-已废弃',
  `qps_limit` int NOT NULL DEFAULT '100' COMMENT 'QPS限制',
  `need_auth` tinyint(1) NOT NULL DEFAULT '1' COMMENT '是否需要鉴权:0-否,1-是',
  `need_desensitize` tinyint(1) NOT NULL DEFAULT '1' COMMENT '是否需要脱敏:0-否,1-是',
  `request_param` text COMMENT '请求参数定义(JSON)',
  `response_param` text COMMENT '响应参数定义(JSON)',
  `request_example` text COMMENT '请求示例',
  `response_example` text COMMENT '响应示例',
  `publish_time` datetime DEFAULT NULL COMMENT '发布时间',
  `offline_time` datetime DEFAULT NULL COMMENT '下线时间',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `create_by` bigint DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT NULL COMMENT '创建时间',
  `update_by` bigint DEFAULT NULL COMMENT '更新人',
  `update_time` datetime DEFAULT NULL COMMENT '更新时间',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除:0-否,1-是',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_api_code_version` (`api_code`,`api_version`,`deleted`),
  KEY `idx_dept_code` (`dept_code`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='API信息表';


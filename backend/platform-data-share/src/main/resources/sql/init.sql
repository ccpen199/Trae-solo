  `hash_algorithm` varchar(20) DEFAULT 'SHA-256' COMMENT '哈希算法',
  `api_id` bigint DEFAULT NULL COMMENT '关联API ID(空表示全局规则)',
  `api_code` varchar(100) DEFAULT NULL COMMENT '关联API编码',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序',
  `enabled` tinyint(1) NOT NULL DEFAULT '1' COMMENT '是否启用:0-否,1-是',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `create_by` bigint DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT NULL COMMENT '创建时间',
  `update_by` bigint DEFAULT NULL COMMENT '更新人',
  `update_time` datetime DEFAULT NULL COMMENT '更新时间',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除:0-否,1-是',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_rule_code` (`rule_code`,`deleted`),
  KEY `idx_api_id` (`api_id`)
